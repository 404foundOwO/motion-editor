#!/usr/bin/env python3
"""Bundle the multi-file app into ONE offline file: dist/motion-editor.html

Usage: python3 tools/build.py [output]
Reads index.html, then inlines css/*.css (fonts as base64), vendor/*.js and js/*.js.
three.js and GLTFLoader are embedded as inert text and loaded lazily, as in the multi-file version.
"""
import re, sys, base64, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'dist', 'motion-editor.html')
rd = lambda p: open(os.path.join(ROOT, p), encoding='utf-8').read()

html = rd('index.html')

def css(m):
    c = rd(m.group(1))
    c = re.sub(r'url\(\.\./(fonts/[^)]+)\)',
               lambda u: 'url(data:font/woff2;base64,' + base64.b64encode(open(os.path.join(ROOT, u.group(1)), 'rb').read()).decode() + ')', c)
    return '<style>' + c + '</style>'
html = re.sub(r'<link rel=stylesheet href="([^"]+)">', css, html)

html = re.sub(r'<script src="((?:js|vendor/(?:mp4|webm)-muxer)[^"]*)"></script>',
              lambda m: '<script>' + rd(m.group(1)).rstrip('\n') + '</script>', html)

# the lazy 3D libraries: embed as text, swap the loader to read them from the page
ld_old = re.search(r"const LDS=\{\},ld=u=>.*?\}\)\);\n?", html, re.S).group(0)
ld_new = ("const LDS={},ld=u=>LDS[u]||(LDS[u]=new Promise((ok,no)=>{const id=u.includes('GLTFLoader')?'lib-gltf':'lib-three',"
          "el=document.getElementById(id);if(!el)return no(new Error('missing library '+u));"
          "try{const sc=document.createElement('script');sc.textContent=el.textContent;document.head.appendChild(sc);ok()}catch(e){no(e)}}));\n")
html = html.replace(ld_old, ld_new, 1)
libs = ''.join('<script type="text/plain" id="%s">%s</script>\n' % (i, rd(p)) for i, p in
               (('lib-three', 'vendor/three.min.js'), ('lib-gltf', 'vendor/GLTFLoader.js')))
html = html.replace('</body>', libs + '</body>', 1)

header = ("<!--\nMotion Editor - standalone build (single file, works offline). Generated by tools/build.py; edit the files in js/ and css/, not this one.\n"
          "Bundles: three.js r128 (MIT), mp4-muxer and webm-muxer (MIT), Roboto Flex and Inter variable fonts (SIL OFL 1.1). Licenses: THIRD_PARTY_NOTICES.md\n-->\n")
html = html.replace('<!DOCTYPE html>\n', '<!DOCTYPE html>\n' + header, 1)
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, 'w', encoding='utf-8').write(html)
print('wrote', out, round(len(html) / 1e6, 2), 'MB')
